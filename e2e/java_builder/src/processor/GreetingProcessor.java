package processor;

import java.io.IOException;
import java.io.Writer;
import java.util.Set;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.PackageElement;
import javax.lang.model.element.TypeElement;

@SupportedAnnotationTypes("greet.Greet")
public final class GreetingProcessor extends AbstractProcessor {
  @Override
  public SourceVersion getSupportedSourceVersion() {
    return SourceVersion.latestSupported();
  }

  @Override
  public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment round) {
    for (TypeElement annotation : annotations) {
      for (Element element : round.getElementsAnnotatedWith(annotation)) {
        String pkg = ((PackageElement) element.getEnclosingElement()).getQualifiedName().toString();
        String name = element.getSimpleName() + "_Greeting";
        try (Writer out = processingEnv.getFiler().createSourceFile(pkg + "." + name, element).openWriter()) {
          out.write("package " + pkg + ";\n\npublic final class " + name + " {\n  private " + name + "() {}\n\n"
              + "  public static String greeting() {\n    return \"generated by an annotation processor\";\n  }\n}\n");
        } catch (IOException e) {
          throw new IllegalStateException(e);
        }
      }
    }
    return true;
  }
}
