#!/usr/bin/env bash
# Run real-runtime fixtures and inspect outputs, using the same commands as CI.
set -euo pipefail
repo="$(cd "$(dirname "$0")/.." && pwd)"
suite="${1:-all}"
if [[ $# -gt 0 ]]; then shift; fi
case "$suite" in jvm|java_builder|kotlin|python|cc|all) ;; *) echo "Usage: $0 [jvm|java_builder|kotlin|python|cc|all] [Bazel build options...]" >&2; exit 2 ;; esac
if [[ "$suite" == jvm || "$suite" == all ]]; then
  (
    cd "$repo/e2e/integration"
    bazel build :javadoc :source_archive :dependencies :bytecode :bindings "$@"
    for workers in true false; do
      bazel build :uses_one_dep :unused_inputs_report :app :kt_app \
        --@rules_elide//elide:emit_jdeps=true \
        --@rules_elide//elide:prune_unused_inputs=true \
        --@rules_elide//elide:use_workers="$workers" \
        --output_groups=+jdeps,+unused_inputs --remote_download_outputs=all "$@"
      python3 verify_jvm_tools.py
    done
    bazel build :app :kt_app \
      --@rules_elide//config/javac:abi_compile_avoidance=true \
      --@rules_elide//config/kotlinc:abi_compile_avoidance=true "$@"
    bazel test :HelloTest "$@"
    python3 verify_pruning.py "$@"
    python3 verify_fused_abi.py "$@"
    python3 verify_kotlin_interop.py "$@"
    python3 verify_incremental.py "$@"
  )
fi
if [[ "$suite" == java_builder || "$suite" == all ]]; then
  (
    cd "$repo/e2e/java_builder"
    log="$(mktemp)"
    trap 'rm -f "$log"' EXIT
    jars=(bazel-bin/libgreeter.jar bazel-bin/libgreet.jar bazel-bin/libapp_lib.jar)
    # Execute every compile (no cache hits), so the route log is printed and the
    # two builds below are independent compiles of the same inputs.
    compile() {
      bazel clean
      if ! bazel build //:app --noremote_accept_cached --remote_download_outputs=all "$@" 2>"$log"; then
        cat "$log" >&2
        exit 1
      fi
    }
    compile "$@"
    if ! grep -q '\[elide-javabuilder\] ELIDE' "$log"; then
      cat "$log" >&2
      echo "java_library compiles were not routed through elide javac" >&2
      exit 1
    fi
    first="$(sha256sum "${jars[@]}")"
    compile "$@"
    if [[ "$first" != "$(sha256sum "${jars[@]}")" ]]; then
      echo "JavaBuilder shim jars are not byte-reproducible across clean builds" >&2
      exit 1
    fi
    expected="Hello, Bazel, from elide javac, generated by an annotation processor"
    actual="$(bazel run //:app "$@" 2>/dev/null)"
    if [[ "$actual" != "$expected" ]]; then
      echo "Unexpected //:app output: $actual" >&2
      exit 1
    fi
    echo "JavaBuilder shim: elide javac route, reproducible jars, and runtime output verified."
  )
fi
if [[ "$suite" == kotlin || "$suite" == all ]]; then
  (
    cd "$repo/e2e/kotlin_builder"
    # The verifier reads intermediate ABI/jdeps outputs outside Bazel. Materialize
    # them even on disk/remote cache hits (toplevel downloads omit these files).
    bazel build :greeter :annotated :symbols :kapt_sources :ksp_sources \
      --output_groups=+generated_classes,+stubs --remote_download_outputs=all "$@"
    python3 verify_outputs.py
  )
fi
if [[ "$suite" == python || "$suite" == all ]]; then
  (
    cd "$repo/e2e/python_overlay"
    bazel test :runtime_test \
      --@rules_python//python/config_settings:bootstrap_impl=system_python "$@"
    bazel test :runtime_test :versioned_test :other_version_test :bazel_env_test "$@"
    bazel build :app :python :java "$@"
    python3 verify_no_host_python.py
    failure_log="$(mktemp)"
    trap 'rm -f "$failure_log"' EXIT
    if bazel test :intentional_failure --test_output=errors "$@" >"$failure_log" 2>&1; then
      cat "$failure_log"
      echo "Expected the intentional Python test failure to fail Bazel" >&2
      exit 1
    fi
    if ! grep -q 'AssertionError: intentional Python test failure' "$failure_log"; then
      cat "$failure_log"
      echo "Negative fixture failed for an unexpected reason" >&2
      exit 1
    fi
    echo "Bazel correctly rejects failing Python tests."
  )
fi
# The cc suite needs the Linux x86-64 distribution; run it under `all` only there.
if [[ "$suite" == cc || ( "$suite" == all && "$(uname -sm)" == "Linux x86_64" ) ]]; then
  (
    cd "$repo/e2e/cc"
    # Hide host compilers: actions run with an empty environment, but also prove
    # the build never needs cc/gcc/clang/ld from PATH. Keep only Bazel itself.
    tool_dir="$(mktemp -d)"
    trap 'rm -rf "$tool_dir"' EXIT
    bazel_path="$(command -v bazel)"
    ln -s "$bazel_path" "$tool_dir/bazel"
    sandbox=(--spawn_strategy=linux-sandbox)
    # The hermetic sandbox exposes only declared inputs plus the loader/libc
    # that the bundled clang binary itself links against.
    if [[ "${ELIDE_CC_HERMETIC_SANDBOX:-1}" == 1 ]]; then
      sandbox+=(--experimental_use_hermetic_linux_sandbox)
      for dir in /lib64 /usr/lib64 /lib/x86_64-linux-gnu /usr/lib/x86_64-linux-gnu; do
        if [[ -d "$dir" ]]; then sandbox+=("--sandbox_add_mount_pair=$dir"); fi
      done
    fi
    PATH="$tool_dir" bazel build :hello "${sandbox[@]}" "$@"
    python3 verify_hermetic_cc.py "$tool_dir/bazel"
  )
fi
